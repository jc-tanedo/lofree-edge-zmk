"""Generate Studio geometry in the *transform's* order, not the UI array order."""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "firmware/lofree_edge"
layout = (ROOT / "web/dist/layout.js").read_text()
keys = sorted(json.loads(re.search(r"KEY_LAYOUT = (\[.*?\]);", layout).group(1)),
              key=lambda key: key["slot"])
assert len(keys) == 84
assert keys[76]["label"] == "Space" and keys[79]["label"] == "Fn"
source = (OUT / "lofree_edge.keymap").read_text()
assert source.count("&trans /* U */") == 1
source = source.replace("&trans /* U */", "&studio_unlock /* U: unlock Studio */")
# Keep the upstream implementations and metadata for useful reassignment actions.
kept = "NONE TOG TO".split()
source = "\n".join(f"#define ZMK_BEHAVIORS_KEEP_{name}" for name in kept) + "\n" + source
source = source.replace("base_layer { bindings", 'base_layer { display-name = "Base"; bindings')
source = source.replace("fn_layer { bindings", 'fn_layer { display-name = "Fn"; bindings')
assert source.endswith("}; };\n")
source = source[:-7] + "\n" + "\n".join(
    f' extra_{n} {{ status = "reserved"; display-name = "Layer {n}"; bindings = <'
    + " &trans" * 84 + " >; };" for n in (2,)) + "\n}; };\n"
if '--ble' in sys.argv:
    source = '#define ZMK_BEHAVIORS_KEEP_BT\n#define ZMK_BEHAVIORS_KEEP_OUT\n#include <dt-bindings/zmk/bt.h>\n#include <dt-bindings/zmk/outputs.h>\n' + source
    for legend, binding in {'1':'&bt BT_SEL 0','2':'&bt BT_SEL 1','3':'&bt BT_SEL 2','4':'&out OUT_USB','5':'&out OUT_BLE','BackSpace':'&bt BT_CLR'}.items():
        marker=f'&trans /* {legend} */'
        assert source.count(marker)==1
        source=source.replace(marker,f'{binding} /* {legend} */')
    (OUT / 'studio-ble.keymap').write_text(source)
else:
    (OUT / 'studio.keymap').write_text(source)
geometry = ["/* Generated by tools/generate_edge_studio.py. */",
            "#include <physical_layouts.dtsi>", "/ {",
            " chosen { /delete-property/ zmk,matrix-transform;",
            "          zmk,physical-layout = &edge_physical_layout;",
            "          zmk,studio-rpc-uart = &edge_studio_uart; };",
            " edge_physical_layout: edge_physical_layout {",
            '  compatible = "zmk,physical-layout"; display-name = "Lofree Edge 84";',
            "  transform = <&edge_transform>; kscan = <&kscan0>;", "  keys ="]
for index, key in enumerate(keys):
    # The existing app uses 26px for one keyunit. ZMK attributes use centikeyunits.
    attrs = [round(key[field] * 100 / 26) for field in ("width", "height", "x", "y")]
    geometry.append("   <&key_physical_attrs " + " ".join(map(str, attrs))
                    + " 0 0 0>" + ("," if index < 83 else ";")
                    + f' /* position {index}, slot {key["slot"]}: {key["label"]} */')
geometry += [" };", "};", "&usbd { edge_studio_uart: edge_studio_uart {",
             ' compatible = "zephyr,cdc-acm-uart";', "}; };", ""]
(OUT / "studio.overlay").write_text("\n".join(geometry))
print("Generated official Studio layout: 84 positions, Base/Fn + 1 reserved layer; Fn+U unlock")
