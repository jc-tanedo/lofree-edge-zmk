"""Generate Edge transform/keymap from physically tested stock slot records."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
keys = sorted(json.loads((root / 'data/edge-visible-key-map.json').read_text()),
              key=lambda k: k['slots'][0])
assert len(keys) == 84
assert len({k['slots'][0] for k in keys}) == 84
bindings = []
for key in keys:
    kind, modifier, usage = key['default_triple']
    if (kind, modifier, usage) == (0xa0, 1, 0):
        binding = '&mo 1'
    elif kind == 0x20 and modifier == 0:
        binding = f'&kp ZMK_HID_USAGE(HID_USAGE_KEY, 0x{usage:02x})'
    elif kind == 0x20 and usage == 0 and modifier and modifier & (modifier - 1) == 0:
        binding = f'&kp ZMK_HID_USAGE(HID_USAGE_KEY, 0x{0xe0 + modifier.bit_length()-1:02x})'
    else:
        raise ValueError(f'Unsupported visible assignment: {key}')
    bindings.append(binding)
out = root / 'firmware/lofree_edge'
transform = ['/* Generated draft; see matrix-evidence.md. */',
             '#include <dt-bindings/zmk/matrix_transform.h>',
             '/ { edge_transform: edge_transform {',
             ' compatible = "zmk,matrix-transform";',
             ' rows = <6>; columns = <15>;', ' map = <']
for key in keys:
    row, col = divmod(key['slots'][0], 15)
    transform.append(f'  RC({row},{col}) /* slot {key["slots"][0]}: {key["tooltip"]} */')
transform += [' >;', '}; };', '']
(out / 'lofree_edge-transform.dtsi').write_text('\n'.join(transform))
keymap = ['/* Generated by tools/generate_edge_zmk.py; Fn+Space preserves stock recovery. */',
          '#include <behaviors.dtsi>', '#include <dt-bindings/zmk/keys.h>',
          '#include <dt-bindings/zmk/backlight.h>',
          '/ { keymap { compatible = "zmk,keymap";', ' base_layer { bindings = <']
keymap += ['  ' + b for b in bindings]
keymap += [' >; };', ' fn_layer { bindings = <']
# Standard consumer usages match stock F1/F2 and F7..F12. F5/F6 now
# control the implemented backlight instead of vendor-only actions.
fn_usage = {0x3a: '&kp C_BRIGHTNESS_DEC', 0x3b: '&kp C_BRIGHTNESS_INC',
            0x3c: '&kp LG(TAB)', 0x3d: '&kp C_AC_SEARCH',
            0x3e: '&bl BL_DEC', 0x3f: '&bl BL_INC',
            0x40: '&kp C_PREVIOUS', 0x41: '&kp C_PLAY_PAUSE',
            0x42: '&kp C_NEXT', 0x43: '&kp C_MUTE',
            0x44: '&kp C_VOLUME_DOWN', 0x45: '&kp C_VOLUME_UP',
            0x29: '&bl BL_TOG', 0x52: '&bl BL_INC', 0x51: '&bl BL_DEC'}
for key in keys:
    kind, modifier, usage = key['default_triple']
    binding = '&prev_fw' if key['slots'][0] == 80 else (
        fn_usage.get(usage, '&trans') if kind == 0x20 and modifier == 0 else '&trans')
    keymap.append(f'  {binding} /* {key["tooltip"]} */')
keymap += [' >; };', '}; };', '']
(out / 'lofree_edge.keymap').write_text('\n'.join(keymap))
print(f'Generated {len(keys)} unique slots, {len(bindings)} base and Fn bindings')
